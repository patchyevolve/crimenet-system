@dataclass
class ConfidenceSchema:
    """Unified confidence with decomposition — per docs"""
    score: float  # 0.0 - 1.0
    basis: List[str] = field(default_factory=list)
    supporting_count: int = 0
    contradicting_count: int = 0
    unknown_count: int = 0
    source_reliability: float = 0.0
    derivation_depth: int = 0  # 0=raw, 1=inferred, 2=derived
    is_independent: bool = True
    last_verified: Optional[str] = None
    staleness: str = "current"  # current/recent/old/very_old
    semantic_type: str = ""     # "observation" | "inference" | "hypothesis"
    run_id: str = ""            # Which pipeline run produced this
    model_version: str = ""     # Which model version produced this
    factors: List[ConfidenceFactor] = field(default_factory=list)  # Structured decomposition

    def __post_init__(self):
        """Auto-populate factors if empty."""
        if not self.factors:
            self.factors = [
                ConfidenceFactor(
                    factor_type="source_reliability",
                    value=self.source_reliability if self.source_reliability > 0 else 0.5,
                    weight=0.4,
                    description=f"Source reliability: {self.source_reliability:.2f}",
                ),
                ConfidenceFactor(
                    factor_type="evidence_basis",
                    value=min(1.0, self.score),
                    weight=0.6,
                    description=self.basis[0] if self.basis else "No basis specified",
                ),
            ]

    @classmethod
    def create(cls, score: float, basis: List[str], source_type: str = "text",
               epistemic: str = "observation", derivation_depth: int = 0,
               run_id: str = "") -> "ConfidenceSchema":
        """Create ConfidenceSchema with proper factors from source type."""
        reliability = get_reliability(source_type, "occurrence") if source_type else 0.5
        factors = [
            ConfidenceFactor(
                factor_type="source_reliability",
                value=reliability,
                weight=0.4,
                description=f"Reliability for {source_type} source",
            ),
            ConfidenceFactor(
                factor_type="evidence_basis",
                value=min(1.0, score),
                weight=0.6,
                description=basis[0] if basis else "",
            ),
        ]
        return cls(
            score=score,
            basis=basis,
            source_reliability=reliability,
            derivation_depth=derivation_depth,
            semantic_type=epistemic,
            run_id=run_id,
            factors=factors,
        )

    def to_dict(self):
        return {
            "score": self.score,
            "basis": self.basis,
            "supporting_count": self.supporting_count,
            "contradicting_count": self.contradicting_count,
            "unknown_count": self.unknown_count,
            "source_reliability": self.source_reliability,
            "derivation_depth": self.derivation_depth,
            "is_independent": self.is_independent,
            "last_verified": self.last_verified,
            "staleness": self.staleness,
            "semantic_type": self.semantic_type,
            "run_id": self.run_id,
            "model_version": self.model_version,
            "factors": [f.to_dict() for f in self.factors],
        }


