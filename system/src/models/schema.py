@dataclass
class EvidenceIntegrity:
    """Chain of custody for evidence — per docs"""
    file_hash: str                  # SHA-256 of original file
    original_filename: str
    ingestion_time: str
    case_id: str = ""               # FK → Case
    jurisdiction_node_id: str = ""  # FK → JurisdictionNode
    chain_of_custody: List[dict] = field(default_factory=list)
    # Each entry: {action: "ingested"|"transformed"|"accessed", timestamp, by, hash_before, hash_after}
    transformations: List[dict] = field(default_factory=list)
    # Each entry: {type: "ocr"|"encoding"|"trimming", input_hash, output_hash, timestamp}

    def add_custody_event(self, action: str, by: str = "system", hash_before: str = "", hash_after: str = ""):
        self.chain_of_custody.append({
            "action": action,
            "timestamp": datetime.now().isoformat(),
            "by": by,
            "hash_before": hash_before,
            "hash_after": hash_after,
        })

    def add_transformation(self, transform_type: str, input_hash: str, output_hash: str):
        self.transformations.append({
            "type": transform_type,
            "input_hash": input_hash,
            "output_hash": output_hash,
            "timestamp": datetime.now().isoformat(),
        })

    def to_dict(self):
        return {
            "file_hash": self.file_hash,
            "original_filename": self.original_filename,
            "ingestion_time": self.ingestion_time,
            "chain_of_custody": self.chain_of_custody,
            "transformations": self.transformations,
        }


